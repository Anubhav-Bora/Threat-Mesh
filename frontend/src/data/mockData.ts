const ago = (days: number, hours = 0) => {
  const value = new Date();
  value.setUTCDate(value.getUTCDate() - days);
  value.setUTCHours(value.getUTCHours() - hours);
  return value.toISOString();
};

const indicator = (
  id: number,
  value: string,
  type: Indicator['type'],
  family: string,
  confidence: number,
  location: [string, string, string, number, number],
  source: string,
  techniques: string[],
  campaignId: string | undefined,
  daysAgo: number,
  asn: [string, string],
  tags: string[],
): Indicator => ({
  id: `ioc-${String(id).padStart(4, '0')}`,
  value,
  type,
  malwareFamily: family,
  confidence,
  isDemo: true,
  country: location[0],
  countryCode: location[1],
  city: location[2],
  latitude: location[3],
  longitude: location[4],
  locationPrecisionKm: 25,
  sourceFeed: source,
  techniqueIds: techniques,
  campaignId,
  firstSeen: ago(daysAgo + 5),
  lastSeen: ago(daysAgo),
  status: null,
  corroboratingFeeds: confidence >= 90 ? 3 : confidence >= 75 ? 2 : 1,
  asn: asn[0],
  asnOrg: asn[1],
  tags,
});

